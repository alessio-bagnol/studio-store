-- SCHEMA STUDIO STORE - SUPABASE POSTGRESQL + SÉCURITÉ RLS
-- ========================================================

-- 1. Table des catégories
create table if not exists public.categories (
    id bigint generated by default as identity primary key,
    name text not null unique,
    icon text default '🏷️',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Insertion des catégories par défaut
insert into public.categories (name, icon)
values ('Puff', '🚬'), ('Airpods', '🎧')
on conflict (name) do nothing;

-- 2. Table des produits
create table if not exists public.products (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null,
    price text not null default '20,00 €',
    old_price text default '',
    description text default '',
    image text default '',
    stock integer default 5,
    incoming_stock integer default 0,
    available_at text default '',
    flavors text default '',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. Table des formules / lots
create table if not exists public.formules (
    id bigint generated by default as identity primary key,
    category text not null,
    qty integer not null,
    price text not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

insert into public.formules (category, qty, price) values
('Puff', 2, '35,00 €'),
('Puff', 3, '50,00 €'),
('Puff', 5, '75,00 €'),
('Puff', 10, '140,00 €'),
('Airpods', 2, '80,00 €')
on conflict do nothing;

-- 4. Table des codes promos
create table if not exists public.promocodes (
    id bigint generated by default as identity primary key,
    code text not null unique,
    discount_percent integer not null,
    active integer default 1,
    max_uses integer default 100,
    times_used integer default 0,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 5. Table des commandes
create table if not exists public.orders (
    id text primary key,
    customer_name text,
    customer_email text,
    customer_phone text,
    customer_address text,
    items jsonb,
    total_amount text,
    status text default 'en_attente',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. Activer Row Level Security (RLS) pour sécuriser l'accès
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.formules enable row level security;
alter table public.promocodes enable row level security;
alter table public.orders enable row level security;

-- Politiques de lecture publique (Tous les visiteurs peuvent consulter le catalogue)
drop policy if exists "Public Read Categories" on public.categories;
create policy "Public Read Categories" on public.categories for select using (true);

drop policy if exists "Public Read Products" on public.products;
create policy "Public Read Products" on public.products for select using (true);

drop policy if exists "Public Read Formules" on public.formules;
create policy "Public Read Formules" on public.formules for select using (true);

drop policy if exists "Public Read Promocodes" on public.promocodes;
create policy "Public Read Promocodes" on public.promocodes for select using (true);

drop policy if exists "Public Read Orders" on public.orders;
create policy "Public Read Orders" on public.orders for select using (true);

-- Politiques de gestion (Création, modification, suppression)
drop policy if exists "Enable all for categories" on public.categories;
create policy "Enable all for categories" on public.categories for all using (true) with check (true);

drop policy if exists "Enable all for products" on public.products;
create policy "Enable all for products" on public.products for all using (true) with check (true);

drop policy if exists "Enable all for formules" on public.formules;
create policy "Enable all for formules" on public.formules for all using (true) with check (true);

drop policy if exists "Enable all for promocodes" on public.promocodes;
create policy "Enable all for promocodes" on public.promocodes for all using (true) with check (true);

drop policy if exists "Enable all for orders" on public.orders;
create policy "Enable all for orders" on public.orders for all using (true) with check (true);

-- 7. Bucket de stockage pour les images de produits (Drag & Drop)
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Public Access Product Images" on storage.objects;
create policy "Public Access Product Images" on storage.objects for select using (bucket_id = 'product-images');

drop policy if exists "Upload Product Images" on storage.objects;
create policy "Upload Product Images" on storage.objects for insert with check (bucket_id = 'product-images');

drop policy if exists "Update Product Images" on storage.objects;
create policy "Update Product Images" on storage.objects for update with check (bucket_id = 'product-images');

drop policy if exists "Delete Product Images" on storage.objects;
create policy "Delete Product Images" on storage.objects for delete using (bucket_id = 'product-images');
